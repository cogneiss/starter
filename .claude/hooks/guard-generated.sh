#!/usr/bin/env sh
#
# PreToolUse guard. AGENTS.md, CLAUDE.md, GEMINI.md and the nested AGENTS.md
# files are generated; a hand edit is overwritten and fails the drift tests.
# Nested files are told apart from hand-written ones by their generated marker.

command -v php >/dev/null 2>&1 || exit 0

input="$(cat)"

path="$(printf '%s' "$input" | php -r '$v = json_decode(stream_get_contents(STDIN), true); echo $v["tool_input"]["file_path"] ?? "";')"
path="${path#"${CLAUDE_PROJECT_DIR:-}"/}"

generated=0
case "$path" in
    AGENTS.md|CLAUDE.md|GEMINI.md|.cursor/rules/laravel-boost.mdc|.junie/guidelines.md) generated=1 ;;
    */AGENTS.md)
        if grep -q 'Generated by `php artisan agents:context`' "${CLAUDE_PROJECT_DIR:-.}/$path" 2>/dev/null; then
            generated=1
        fi ;;
esac

if [ "$generated" = 1 ]; then
    reason="$path is generated. Edit .ai/guidelines/*.blade.php or .ai/rules/index.md, then run: php artisan boost:install --guidelines --skills --no-interaction && cp AGENTS.md GEMINI.md && php artisan agents:context"
    php -r 'echo json_encode(["hookSpecificOutput" => ["hookEventName" => "PreToolUse", "permissionDecision" => "deny", "permissionDecisionReason" => $argv[1]]]);' -- "$reason"
fi

exit 0
