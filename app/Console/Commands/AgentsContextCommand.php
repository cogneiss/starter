<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Symfony\Component\Finder\Finder;

/**
 * Writes a nested `AGENTS.md` into each directory `.ai/rules/index.md` names, so
 * an agent that reads nested AGENTS.md (Codex, Copilot, Cursor, Gemini, Amp)
 * learns which rule files and skill to open before editing there. Claude Code
 * needs none: `.claude/rules` is a symlink to `.ai/rules` and loads each rule by
 * its `paths:` frontmatter already, which is more than a pointer would add.
 *
 * The index is the only source, so there is nothing to keep in step by hand.
 * Output is marked, which lets a run remove a file whose directory left the
 * index, and `--check` fails on any difference without writing.
 */
#[Description('Write nested AGENTS.md files from .ai/rules/index.md, or with --check fail when they are out of date')]
#[Signature('agents:context {--check : Fail instead of writing when a nested file differs} {--root= : The project root, defaults to the application base path}')]
final class AgentsContextCommand extends Command
{
    public const string MARKER = '<!-- Generated by `php artisan agents:context` from .ai/rules/index.md. Do not edit. -->';

    /**
     * `app` would repeat app.md over every child; `wiki` holds pages that the wiki lint reads, and a stray file there fails it.
     */
    private const array SKIPPED = ['app', 'wiki'];

    /**
     * The rule files that have a skill carrying their procedure.
     *
     * @var array<string, string>
     */
    private const array SKILLS = [
        '.ai/rules/ai.md' => 'ai-layer',
        '.ai/rules/app.md' => 'org-access',
        '.ai/rules/policies.md' => 'org-access',
        '.ai/rules/platform-ops.md' => 'platform-ops',
        '.ai/rules/resources.md' => 'resource-spine',
        '.ai/rules/ux.md' => 'ux-kit',
    ];

    private const array SKIPPED_DIRECTORIES = ['node_modules', 'vendor', 'storage'];

    public function handle(): int
    {
        $root = $this->option('root');
        $root = is_string($root) && $root !== '' ? $root : base_path();

        $expected = $this->expected($root);
        $stale = $this->generatedFiles($root, array_keys($expected));
        $differs = array_keys(array_filter(
            $expected,
            fn (string $contents, string $path): bool => ! is_file($root.'/'.$path) || file_get_contents($root.'/'.$path) !== $contents,
            ARRAY_FILTER_USE_BOTH,
        ));

        if ($this->option('check')) {
            return $this->report($differs, $stale);
        }

        foreach ($differs as $path) {
            File::put($root.'/'.$path, $expected[$path]);
        }

        foreach ($stale as $path) {
            File::delete($root.'/'.$path);
        }

        $this->components->info(sprintf('Wrote %d nested AGENTS.md file(s), removed %d.', count($differs), count($stale)));

        return self::SUCCESS;
    }

    /**
     * @param  list<string>  $differs
     * @param  list<string>  $stale
     */
    private function report(array $differs, array $stale): int
    {
        if ($differs === [] && $stale === []) {
            $this->components->info('Nested AGENTS.md files are current.');

            return self::SUCCESS;
        }

        foreach ([...$differs, ...$stale] as $path) {
            $this->line('  '.$path);
        }

        $this->components->error('Nested AGENTS.md files are out of date. Run `php artisan agents:context` and commit the result.');

        return self::FAILURE;
    }

    /**
     * @return array<string, string> path relative to the root, then contents
     */
    private function expected(string $root): array
    {
        $rows = $this->rows($root);
        $files = [];

        foreach ($rows as [$globs]) {
            foreach ($globs as $glob) {
                if (preg_match('#^([^*{}]+)/\*\*$#', $glob, $found) !== 1) {
                    continue;
                }

                $directory = $found[1];

                if (in_array($directory, self::SKIPPED, true) || str_starts_with($directory, '.') || ! is_dir($root.'/'.$directory)) {
                    continue;
                }

                $files[$directory.'/AGENTS.md'] = $this->render($directory, $rows);
            }
        }

        return $files;
    }

    /**
     * @return list<array{0: list<string>, 1: string}> globs, then the rule file
     */
    private function rows(string $root): array
    {
        $rows = [];

        foreach (explode("\n", (string) file_get_contents($root.'/.ai/rules/index.md')) as $line) {
            if (preg_match('/^\| (.+?) \| (\.ai\/rules\/\S+\.md) \|$/', $line, $cells) !== 1) {
                continue;
            }

            $globs = preg_split('/,\s*(?![^{}]*\})/', $cells[1]);
            $rows[] = [$globs === false ? [] : $globs, $cells[2]];
        }

        return $rows;
    }

    /**
     * @param  list<array{0: list<string>, 1: string}>  $rows
     */
    private function render(string $directory, array $rows): string
    {
        $rules = [];

        foreach ($rows as [$globs, $rule]) {
            foreach ($globs as $glob) {
                if ($glob !== '**' && $this->matches($glob, $directory.'/file')) {
                    $rules[] = $rule;

                    break;
                }
            }
        }

        $skills = array_values(array_unique(array_filter(array_map(fn (string $rule): ?string => self::SKILLS[$rule] ?? null, $rules))));

        $text = self::MARKER."\n\n# Before you edit `".$directory."`\n\nRead each of these, then follow them:\n\n";
        $text .= implode("\n", array_map(fn (string $rule): string => '- `'.$rule.'`', $rules))."\n";

        if ($skills !== []) {
            $text .= "\nLoad the matching skill before you start:\n\n";
            $text .= implode("\n", array_map(fn (string $skill): string => '- `'.$skill.'` (`.ai/skills/'.$skill.'/SKILL.md`)', $skills))."\n";
        }

        return $text."\nThe root `AGENTS.md` carries what every task needs.\n";
    }

    private function matches(string $glob, string $path): bool
    {
        $pattern = strtr(preg_quote($glob, '#'), ['\*\*' => '.*', '\*' => '[^/]*']);

        return preg_match('#^'.$pattern.'$#', $path) === 1;
    }

    /**
     * Marked files outside the expected set: leftovers of a directory that left the index.
     *
     * @param  list<string>  $expected
     * @return list<string>
     */
    private function generatedFiles(string $root, array $expected): array
    {
        $stale = [];

        $finder = Finder::create()->files()->in($root)->name('AGENTS.md')->exclude(self::SKIPPED_DIRECTORIES)->ignoreDotFiles(true)->depth('> 0');

        foreach ($finder as $file) {
            $path = $file->getRelativePathname();

            if (! in_array($path, $expected, true) && str_starts_with($file->getContents(), self::MARKER)) {
                $stale[] = $path;
            }
        }

        return $stale;
    }
}
